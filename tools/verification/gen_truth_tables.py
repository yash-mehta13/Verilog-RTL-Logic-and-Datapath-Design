#!/usr/bin/env python3
"""Generate reference truth/function tables (docs/truth-tables/*.md).

The tables come from small Python reference models (plain integer
arithmetic). They are NOT read from the RTL; the RTL is checked against the
same semantics by the self-checking testbenches. Regenerate with --write,
verify freshness with --check.
"""
import argparse
import itertools
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "truth-tables"
HDR = "<!-- GENERATED by tools/verification/gen_truth_tables.py - do not edit by hand -->\n"


def md(header, rows):
    L = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    L += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(L) + "\n"


def arithmetic():
    t = "# Task I - adder / subtractor truth tables\n\n" + HDR + "\n"
    t += "## Half adder\n\n" + md(["A", "B", "SUM", "CARRY"],
        [[a, b, (a + b) % 2, (a + b) // 2] for a, b in itertools.product((0, 1), repeat=2)])
    t += "\n`SUM = A ⊕ B`, `CARRY = A·B`\n\n## Half subtractor (A - B)\n\n" + md(["A", "B", "DIFF", "BORROW"],
        [[a, b, (a - b) % 2, int(a < b)] for a, b in itertools.product((0, 1), repeat=2)])
    t += "\n`DIFF = A ⊕ B`, `BORROW = A'·B`\n\n## Full adder\n\n" + md(["A", "B", "CIN", "SUM", "COUT", "minterms"],
        [[a, b, c, (a + b + c) % 2, (a + b + c) // 2, f"m{a * 4 + b * 2 + c}"]
         for a, b, c in itertools.product((0, 1), repeat=3)])
    sums = [a * 4 + b * 2 + c for a, b, c in itertools.product((0, 1), repeat=3) if (a + b + c) % 2]
    cos = [a * 4 + b * 2 + c for a, b, c in itertools.product((0, 1), repeat=3) if (a + b + c) // 2]
    t += f"\nSUM = Σm({', '.join(map(str, sums))}),  COUT = Σm({', '.join(map(str, cos))})  (decoder realization uses exactly these lines)\n\n"
    t += "## Full subtractor (A - B - BIN)\n\n" + md(["A", "B", "BIN", "DIFF", "BOUT"],
        [[a, b, c, (a - b - c) % 2, int(a - b - c < 0)] for a, b, c in itertools.product((0, 1), repeat=3)])
    d = [a * 4 + b * 2 + c for a, b, c in itertools.product((0, 1), repeat=3) if (a - b - c) % 2]
    bo = [a * 4 + b * 2 + c for a, b, c in itertools.product((0, 1), repeat=3) if a - b - c < 0]
    t += f"\nDIFF = Σm({', '.join(map(str, d))}),  BOUT = Σm({', '.join(map(str, bo))})\n"
    return "task01_arithmetic.md", t


def mux_dec():
    t = "# Task III - MUX / decoder / encoder tables\n\n" + HDR + "\n"
    t += "## 2:1 MUX\n\n" + md(["S", "Y"], [[0, "D0"], [1, "D1"]])
    t += "\n## 4:1 MUX (s = {s1,s0}, Y = D[s])\n\n" + md(["s1", "s0", "Y"], [[s >> 1, s & 1, f"D{s}"] for s in range(4)])
    t += "\n8:1 and 16:1: `Y = D[s]` with `s` the unsigned binary value of the select bits (s[0] = LSB).\n\n"
    t += "## 1:4 demultiplexer\n\n" + md(["DIN", "s1", "s0", "Y3 Y2 Y1 Y0"],
        [[d, s >> 1, s & 1, format((d << s), "04b")] for d in (0, 1) for s in range(4)])
    t += "\n## 2:4 decoder (EN active-high, outputs active-high)\n\n" + md(["EN", "A1", "A0", "Y3 Y2 Y1 Y0"],
        [[e, a >> 1, a & 1, format((e << a), "04b")] for e in (0, 1) for a in range(4)])
    t += "\nActive-low version (`decoder2to4_n`): `en_n = 0` enables, outputs are the bitwise complement (`y_n = ~y`).\n\n"
    t += "## 4:2 encoder (one-hot assumption) vs 4:2 priority encoder\n\n"
    rows = []
    for d in range(16):
        bits = [(d >> i) & 1 for i in range(4)]
        onehot = sum(bits) == 1
        raw = (bits[2] | bits[3]) * 2 + (bits[1] | bits[3])
        hi = max([i for i in range(4) if bits[i]], default=0)
        rows.append([format(d, "04b"), (format(raw, "02b") if True else ""), int(onehot),
                     format(hi, "02b"), int(d != 0)])
    t += md(["D3..D0", "enc Y1Y0 (raw OR)", "enc valid", "priority Y1Y0", "priority valid"], rows)
    t += "\nFor the simple encoder `Y` is only meaningful when `valid = 1` (exactly one input high).\n"
    return "task03_mux_decoder_encoder.md", t


def alu():
    t = "# Task IV - ALU function table\n\n" + HDR + "\n"
    ops = [("000", "ADD", "y = a + b"), ("001", "SUB", "y = a - b (a + ~b + 1)"), ("010", "AND", "y = a & b"),
           ("011", "OR", "y = a | b"), ("100", "XOR", "y = a ^ b"), ("101", "XNOR", "y = ~(a ^ b)"),
           ("110", "NOT A", "y = ~a"), ("111", "PASS B", "y = b")]
    flags = {"ADD": "C, V", "SUB": "B, V"}
    t += md(["op", "name", "result", "meaningful carry/borrow/overflow", "zero / negative"],
            [[o, n, r, flags.get(n, "none (forced to 0)"), "always from y"] for o, n, r in ops])
    t += ("\nFlags: `carry` = carry out of MSB (ADD only); `borrow` = a < b unsigned (SUB only); "
          "`overflow` = signed overflow (ADD/SUB only); `zero` = (y == 0); `negative` = y[W-1].\n")
    # 1-bit ALU exhaustive table
    t += "\n## 1-bit ALU (W = 1) - all 32 input combinations\n\n"
    rows = []
    for op in range(8):
        for a in (0, 1):
            for b in (0, 1):
                sa, sb = (-a), (-b)           # 1-bit two's complement: 1 -> -1
                carry = borrow = ov = 0
                if op == 0:
                    y = (a + b) % 2; carry = (a + b) // 2; ov = int(not -1 <= sa + sb <= 0)
                elif op == 1:
                    y = (a - b) % 2; borrow = int(a < b); ov = int(not -1 <= sa - sb <= 0)
                else:
                    y = [None, None, a & b, a | b, a ^ b, 1 - (a ^ b), 1 - a, b][op]
                rows.append([format(op, "03b"), a, b, y, carry, borrow, ov, int(y == 0), y])
    t += md(["op", "a", "b", "y", "carry", "borrow", "overflow", "zero", "negative"], rows)
    return "task04_alu.md", t


def build():
    return dict(f() for f in (arithmetic, mux_dec, alu))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    files = build()
    bad = 0
    for name, txt in files.items():
        p = OUT / name
        if a.write:
            OUT.mkdir(parents=True, exist_ok=True)
            p.write_text(txt)
            print("wrote", p.relative_to(ROOT))
        elif a.check and (not p.exists() or p.read_text() != txt):
            print("STALE:", p.relative_to(ROOT), file=sys.stderr)
            bad = 1
    if a.check and not bad:
        print(f"{len(files)} truth-table files up to date")
    return bad


if __name__ == "__main__":
    sys.exit(main())
