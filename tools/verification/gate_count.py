#!/usr/bin/env python3
"""Count and check gate-level netlists written with Verilog primitives.

Used for
  * the NAND-only / NOR-only half/full adder/subtractor modules in
    rtl/arithmetic/nand_nor_arith.v (Task I, item 4), and
  * cross-checking the netlists emitted by tools/boolean_design.

The counter parses primitive instances (and/or/not/nand/nor/xor/xnor) from the
Verilog source; it evaluates the parsed netlist exhaustively in Python and
compares it with an independent reference function, so the reported counts
belong to circuits that were actually checked.

    python tools/verification/gate_count.py            # print report
    python tools/verification/gate_count.py --write    # (re)generate the doc
    python tools/verification/gate_count.py --check    # fail if doc is stale
"""
import argparse
import itertools
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "rtl" / "arithmetic" / "nand_nor_arith.v"
DOC = ROOT / "docs" / "gate-count-analysis" / "task01_nand_nor_gate_counts.md"

PRIM = r"(and|or|not|nand|nor|xor|xnor)"
INST = re.compile(r"^\s*" + PRIM + r"\s+\w+\s*\(([^)]*)\)\s*;", re.M)
ASSIGN = re.compile(r"^\s*assign\s+(\w+)\s*=\s*(\w+)\s*;", re.M)


def module_body(text, name):
    m = re.search(r"module\s+" + re.escape(name) + r"\b(.*?)endmodule", text, re.S)
    if not m:
        raise KeyError(name)
    return m.group(1)


def parse_netlist(text, name):
    """Return (gates, aliases). gates = [(op, out, [ins])] in file order."""
    body = module_body(text, name)
    gates = []
    for m in INST.finditer(body):
        op, args = m.group(1), m.group(2)
        pins = [p.strip() for p in args.split(",")]
        gates.append((op, pins[0], pins[1:]))
    aliases = dict(ASSIGN.findall(body))
    return gates, aliases


def count_primitives(text, name):
    gates, _ = parse_netlist(text, name)
    return Counter(op for op, _, _ in gates)


def evaluate(gates, aliases, inputs):
    val = dict(inputs)
    fn = {"and": lambda v: int(all(v)), "or": lambda v: int(any(v)),
          "not": lambda v: 1 - v[0], "nand": lambda v: 1 - int(all(v)),
          "nor": lambda v: 1 - int(any(v)), "xor": lambda v: sum(v) % 2,
          "xnor": lambda v: 1 - sum(v) % 2}
    for op, out, ins in gates:
        val[out] = fn[op]([val[i] for i in ins])
    for dst, src in aliases.items():
        val[dst] = val[src]
    return val


def depth(gates, aliases, inputs):
    lvl = {i: 0 for i in inputs}
    for op, out, ins in gates:
        lvl[out] = 1 + max(lvl[i] for i in ins)
    for dst, src in aliases.items():
        lvl[dst] = lvl[src]
    return lvl


# Independent reference functions (plain integer arithmetic).
def ref_ha(a, b):  return {"sum": (a + b) % 2, "carry": (a + b) // 2}
def ref_hs(a, b):  return {"diff": (a - b) % 2, "borrow": int(a < b)}
def ref_fa(a, b, c):  return {"sum": (a + b + c) % 2, "cout": (a + b + c) // 2}
def ref_fs(a, b, c):  return {"diff": (a - b - c) % 2, "bout": int(a - b - c < 0)}

CIRCUITS = [  # (title, module stem, inputs, reference)
    ("Half adder", "half_adder", ["a", "b"], ref_ha),
    ("Half subtractor", "half_subtractor", ["a", "b"], ref_hs),
    ("Full adder", "full_adder", ["a", "b", "cin"], ref_fa),
    ("Full subtractor", "full_subtractor", ["a", "b", "bin"], ref_fs),
]


def analyse(text):
    rows = []
    for title, stem, ins, ref in CIRCUITS:
        for kind in ("nand", "nor"):
            name = f"{stem}_{kind}"
            gates, aliases = parse_netlist(text, name)
            bad = 0
            outs = None
            max_depth = 0
            for combo in itertools.product((0, 1), repeat=len(ins)):
                inp = dict(zip(ins, combo))
                v = evaluate(gates, aliases, inp)
                expect = ref(*combo)
                outs = list(expect)
                bad += sum(v[k] != e for k, e in expect.items())
            lv = depth(gates, aliases, ins)
            max_depth = max(lv[o] for o in outs)
            only = {op for op, _, _ in gates}
            assert only == {kind}, (name, only)
            tied = sum(1 for op, o, i in gates if len(i) == 2 and i[0] == i[1])
            rows.append({"title": title, "kind": kind.upper(), "module": name,
                         "gates": len(gates), "inverters": tied, "depth": max_depth,
                         "mismatches": bad, "vectors": 2 ** len(ins)})
    return rows


def render(rows):
    by = {}
    for r in rows:
        by.setdefault(r["title"], {})[r["kind"]] = r
    L = []
    L.append("# Task I - NAND-only and NOR-only gate counts\n")
    L.append("<!-- GENERATED by tools/verification/gate_count.py - do not edit by hand -->\n")
    L.append("Counts are obtained by **parsing the primitive instances** in "
             "[`rtl/arithmetic/nand_nor_arith.v`](../../rtl/arithmetic/nand_nor_arith.v) and "
             "evaluating the parsed netlist for every input vector against an independent "
             "integer-arithmetic reference. The Verilog modules themselves are also verified "
             "by simulation in `tb/task01/tb_half_full_adders.v`.\n")
    L.append("## Counting convention\n")
    L.append("* Only two-input NAND (or NOR) gates are allowed.\n"
             "* An inverter is a two-input gate with both inputs tied together and **is counted as one gate** "
             "(column *tied-input inverters* shows how many of the total are inverters).\n"
             "* A wire alias (e.g. `borrow = n2` in `half_subtractor_nor`) costs no gate.\n"
             "* Logic depth = longest input-to-output path measured in gates.\n"
             "* Counts describe the specific circuits in this repository. They are **not** claimed "
             "to be globally minimal; no exhaustive minimal-network search was performed.\n")
    L.append("## Results\n")
    L.append("| Circuit | NAND gates | NAND inverters | NAND depth | NOR gates | NOR inverters | NOR depth | Fewer gates |")
    L.append("|---|---|---|---|---|---|---|---|")
    for title, d in by.items():
        n, o = d["NAND"], d["NOR"]
        win = "NAND" if n["gates"] < o["gates"] else "NOR" if o["gates"] < n["gates"] else "tie"
        L.append(f"| {title} | {n['gates']} | {n['inverters']} | {n['depth']} | "
                 f"{o['gates']} | {o['inverters']} | {o['depth']} | {win} |")
    L.append("")
    L.append("All eight parsed netlists matched the reference on every input vector "
             "(" + ", ".join(f"{r['vectors']}" for r in rows) + " vectors respectively).\n")
    fa_n, fa_o = by["Full adder"]["NAND"]["gates"], by["Full adder"]["NOR"]["gates"]
    L.append("## 4-bit ripple adders built from these cells\n")
    L.append("| Adder | Gates (4 x full adder) |")
    L.append("|---|---|")
    L.append(f"| `ripple_adder4_nand` | 4 x {fa_n} = {4 * fa_n} two-input NAND |")
    L.append(f"| `ripple_adder4_nor`  | 4 x {fa_o} = {4 * fa_o} two-input NOR |")
    L.append("| `ripple_adder4_gates` (xor/and/or) | 4 x (2 XOR + 2 AND + 1 OR) = 20 gates (mixed types, 2-input) |")
    L.append("")
    L.append("## Justification (specific to the circuits above)\n")
    L.append("* **Shared sub-networks.** In every NAND design the first three gates "
             "(`n1 = nand(a,b)`, `n2 = nand(a,n1)`, `n3 = nand(b,n1)`) form the shared XOR front end; "
             "`n1` also yields the AND/carry term, so the carry costs one extra gate (an inverter) "
             "in the half adder and one gate in the full adder.\n"
             "* **Half subtractor, NOR.** `n2 = nor(a, nor(a,b)) = ~a.b` is exactly the borrow, so the "
             "borrow output is free.\n"
             "* **Why the full subtractor needs more NOR gates.** The borrow expression contains "
             "`~a.b`, and the NOR-based XOR produces XNOR first; recovering the XOR polarity for the "
             "second stage costs extra inverters (see the *NOR inverters* column).\n"
             "* **Comparison.** For these constructions NAND is never worse than NOR and is strictly "
             "better for the half adder and full subtractor. Other realizations may exist; "
             "this report does not prove optimality.\n")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = SRC.read_text()
    rows = analyse(text)
    bad = [r for r in rows if r["mismatches"]]
    out = render(rows)
    for r in rows:
        print(f"{r['module']:24s} gates={r['gates']:2d} inverters={r['inverters']} depth={r['depth']} "
              f"{'OK' if not r['mismatches'] else 'MISMATCH'}")
    if bad:
        print("netlist does not match reference", file=sys.stderr)
        return 1
    if args.write:
        DOC.parent.mkdir(parents=True, exist_ok=True)
        DOC.write_text(out)
        print("wrote", DOC.relative_to(ROOT))
    if args.check:
        if not DOC.exists() or DOC.read_text() != out:
            print("STALE:", DOC.relative_to(ROOT), "- run with --write", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
